// Load, merge, and save each locale file
const locales = ['en', 'hi', 'mr', 'ta', 'bn', 'kn', 'or', 'sa', 'te'];

for (const lang of locales) {
  const filePath = path.join(localesDir, `${lang}.json`);
  const existing = JSON.parse(fs.readFileSync(filePath, 'utf-8'));

  const newKeys = translations[lang];
  if (!newKeys) {
    console.error(`No translations found for ${lang}`);
    continue;
  }

  // Merge new keys into existing admin namespace
  existing.admin = { ...existing.admin, ...newKeys };

  fs.writeFileSync(filePath, JSON.stringify(existing, null, 2) + '\n', 'utf-8');
  console.log(`✅ Updated ${lang}.json with ${Object.keys(newKeys).length} new admin keys`);
}

console.log('\nDone. All 9 locale files updated.');

